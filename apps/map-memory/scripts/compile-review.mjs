// Run after manually reviewing images and editing visual-review.json.
// This command validates and compiles decisions; it never approves new images.
import { readFile, writeFile } from 'node:fs/promises';
import { CITIES, deduplicate } from '../core.mjs';
import { visualGroup } from '../quality.mjs';
const source = new URL('../visual-review.json', import.meta.url);
const review = JSON.parse(await readFile(source, 'utf8'));
const approved = {};
for (const city of CITIES) {
  const row = review.cities.find(entry => entry.id === city.id);
  if (!row) throw new Error(`Missing review for ${city.id}`);
  const ids = new Set();
  for (const image of row.images) {
    if (ids.has(image.id) || !/^[a-f0-9]{64}$/.test(image.sha256) || !['approved', 'excluded'].includes(image.decision) || !image.reason) throw new Error(`Invalid review: ${city.id}/${image.id}`);
    ids.add(image.id);
  }
  const hashes = new Set();
  const maps = deduplicate(row.images.filter(image => image.decision === 'approved').map(image => ({ ...image, visualGroup: visualGroup(image.id, image.title) })));
  approved[city.id] = Object.fromEntries(maps.filter(image => {
    if (hashes.has(image.sha256)) return false;
    hashes.add(image.sha256); return true;
  }).map(image => [image.id, image.sha256]));
}
await writeFile(new URL('../reviewed-maps.mjs', import.meta.url), `// Generated by scripts/compile-review.mjs from visual-review.json.\n// Approval binds a city/resource to the exact visually inspected thumbnail bytes.\nexport const REVIEWED_MAPS = ${JSON.stringify(approved, null, 2)};\n`);
console.log(`Compiled ${Object.values(approved).reduce((sum, maps) => sum + Object.keys(maps).length, 0)} reviewed map images across ${CITIES.length} cities.`);
